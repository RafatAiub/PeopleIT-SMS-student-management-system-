/** Translate with the SMS dictionary first, then the app dictionary. */
export function useSmsT() {
  const lang = useLocaleStore((s) => s.lang);
  const appT = useT();
  return useCallback(
    (key: string, vars?: Record<string, string | number>) => {
      if (lang !== 'bn' || !(key in smsBn)) return appT(key, vars);
      const s = smsBn[key];
      return vars ? s.replace(/\{(\w+)\}/g, (_, k: string) => (k in vars ? String(vars[k]) : `{${k}}`)) : s;
    },
    [lang, appT],
  );
}
